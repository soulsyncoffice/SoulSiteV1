create table if not exists public.decisions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  profile_id text not null,
  decision text not null check (decision in ('yes', 'no')),
  tier text not null default 'Free' check (tier in ('Free', 'Standard', 'Pro')),
  date_key date not null,
  created_at timestamptz not null default now()
);

create index if not exists decisions_user_date_decision_idx
  on public.decisions (user_id, date_key, decision);

create table if not exists public.daily_decision_usage (
  user_id uuid not null references auth.users (id) on delete cascade,
  date_key date not null,
  yes_count integer not null default 0 check (yes_count >= 0),
  primary key (user_id, date_key)
);

alter table public.daily_decision_usage enable row level security;
revoke all on public.daily_decision_usage from public, anon, authenticated;
grant all on public.daily_decision_usage to service_role;

alter table public.decisions enable row level security;

revoke all on public.decisions from anon, authenticated;
grant select on public.decisions to authenticated;

drop policy if exists "Users can read their own decisions" on public.decisions;
create policy "Users can read their own decisions"
  on public.decisions
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own decisions" on public.decisions;

create or replace function public.enforce_daily_yes_limit()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  daily_limit integer;
  next_yes_count integer;
begin
  if new.decision <> 'yes' then
    return new;
  end if;

  daily_limit := case new.tier
    when 'Standard' then 20
    when 'Pro' then 50
    else 5
  end;

  insert into public.daily_decision_usage (user_id, date_key, yes_count)
    values (new.user_id, new.date_key, 1)
    on conflict (user_id, date_key)
    do update set yes_count = public.daily_decision_usage.yes_count + 1
      where public.daily_decision_usage.yes_count < daily_limit
    returning yes_count into next_yes_count;

  if not found then
    raise exception using
      errcode = '23514',
      message = 'daily_yes_limit_reached';
  end if;

  return new;
end;
$$;

drop trigger if exists enforce_daily_yes_limit on public.decisions;
create trigger enforce_daily_yes_limit
  before insert on public.decisions
  for each row
  execute function public.enforce_daily_yes_limit();
